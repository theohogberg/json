#!/usr/bin/env python3
"""Writes src/unicat.h: the Unicode general category of every code point, for
\\p{..} in match() and search(). Rerun to move to a newer Unicode:
    python3 src/unicat.py > src/unicat.h"""
import unicodedata

# the order of enum ucat in json.c
CATS = ("Lu Ll Lt Lm Lo Mn Mc Me Nd Nl No Pc Pd Ps Pe Pi Pf Po "
        "Sm Sc Sk So Zs Zl Zp Cc Cf Cs Co Cn").split()

starts, prev = [], None
for cp in range(0x110000):
    cat = CATS.index(unicodedata.category(chr(cp)))
    if cat != prev:
        starts.append(cp << 5 | cat)
        prev = cat

print("/* generated by src/unicat.py from Unicode %s; do not edit */"
      % unicodedata.unidata_version)
print("/* first code point of each run << 5 | its category (enum ucat) */")
print("static const uint32_t ucat_runs[%d] = {" % len(starts))
for i in range(0, len(starts), 8):
    print("\t" + ", ".join("%d" % s for s in starts[i:i + 8]) + ",")
print("};")
